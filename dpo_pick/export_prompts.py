"""Write PROMPTS.md: the full terra (v1b.1) + luna prompts used by dpo_pick, generated from the code so they cannot drift.
usage: python export_prompts.py      (rerun after changing pairwise_judge.py or luna_checks.py)
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [HERE, os.path.dirname(HERE)]
import luna_checks as L  # noqa: E402
import pairwise_judge as pj  # noqa: E402
from pick_batch import PROMPT  # noqa: E402

fence = lambda s, lang="text": f"```{lang}\n{s.rstrip()}\n```"
out = [f"# dpo_pick prompts (terra {PROMPT} + luna m1)", "",
       "Generated by `export_prompts.py` from `../pairwise_judge.py` and `luna_checks.py`; do not edit by hand.", "",
       "## 1. terra: pairwise judge (decides the pair)", "",
       f"`{pj.MODEL}`, Responses API, reasoning effort `low`, strict JSON. Prompt version **{PROMPT}** (the repository default is "
       "v1b; v1b.1 adds the sentence \"Two valid artistic interpretations of the same request are similar.\" to the photo / "
       "illustration item, followed by a repeat of the sentence before it).", "",
       "Each pair is called in both A/B orders; margin = P(B better) − P(A better) mapped to the same side and averaged; "
       "a pair is kept when the mean |margin| ≥ 0.8.", "",
       "### developer message", "", fence(pj.PROMPTS[PROMPT]), "",
       "### user message (the aspect-ratio line only when the request has one)", "", fence(pj.user_text("<request>", "<aspect ratio>", "<md A>", "<md B>")), "",
       "### output schema", "", fence(json.dumps(pj.SCHEMA, indent=1), "json"), "",
       "## 2. luna: five pointwise checks (only ranks candidate pairs)", "",
       f"`{L.MODEL}`, Decisions API, ONE call per md with five choice questions. prior(md) = sum over the five checks of "
       "P(major); lower = cleaner. Candidate pairs = clean md vs the md with the largest prior gap; luna never decides or "
       "vetoes a pair.", "",
       "### input", "", fence(L.MERGED_PREAMBLE + "\n\n# User request\n<request>\nTarget aspect ratio: <aspect ratio>\n\n# Brief\n<md>"), "",
       "### questions (name: instructions); every question has the same three choices", ""]
for c, t in L.CHECKS.items():
    out += [f"**{c}**", "", fence(t), ""]
out += ["### choices", "", fence(json.dumps(L.SEV, ensure_ascii=False, indent=1), "json"), "",
        "## 3. Hard rule (no model)", "",
        "An md is a hard negative (never chosen, tried first as rejected) when it is not format-valid, did not finish "
        "(`finish_reason != stop`), or matches:", "", fence(L.LOOP_RE.pattern, "regex"), "(case-insensitive)", ""]
open(os.path.join(HERE, "PROMPTS.md"), "w").write("\n".join(out))
print("wrote PROMPTS.md")
